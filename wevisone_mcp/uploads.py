"""Server-issued handle store for uploaded images.

A client never supplies a filesystem path: it uploads bytes, gets back an opaque
``upload_id`` (32 hex chars), and refers to that id later. Ids are generated by
the server, so the id itself cannot carry traversal.

Deliberately stdlib-only so it can be unit-tested without torch or Pillow.
"""

from __future__ import annotations

import os
import re
import secrets
import time
from pathlib import Path

UPLOAD_ID_RE = re.compile(r"^[0-9a-f]{32}$")

DEFAULT_TTL_S = 600


def new_upload_id() -> str:
    """A fresh opaque id: 32 lowercase hex characters."""
    return secrets.token_hex(16)


def store_upload(directory: str | os.PathLike[str], data: bytes) -> tuple[str, int]:
    """Write ``data`` under a fresh id. Returns ``(upload_id, byte_count)``."""
    if not data:
        raise ValueError("upload body is empty")
    target_dir = Path(directory)
    target_dir.mkdir(parents=True, exist_ok=True)
    upload_id = new_upload_id()
    (target_dir / upload_id).write_bytes(data)
    return upload_id, len(data)


def resolve_upload(directory: str | os.PathLike[str], upload_id: str) -> Path:
    """Map an id to its file, rejecting anything that is not a well-formed id."""
    candidate = (upload_id or "").strip()
    if not UPLOAD_ID_RE.match(candidate):
        raise ValueError("upload_id must be 32 lowercase hex characters")
    path = Path(directory) / candidate
    if not path.is_file():
        raise ValueError(f"unknown upload_id {candidate}")
    return path


def sweep(directory: str | os.PathLike[str], ttl_s: int = DEFAULT_TTL_S) -> int:
    """Delete uploads older than ``ttl_s``. Returns how many were removed."""
    target_dir = Path(directory)
    if not target_dir.is_dir():
        return 0
    cutoff = time.time() - ttl_s
    removed = 0
    for entry in target_dir.iterdir():
        if not entry.is_file() or not UPLOAD_ID_RE.match(entry.name):
            continue
        try:
            if entry.stat().st_mtime < cutoff:
                entry.unlink()
                removed += 1
        except OSError:  # a racing sweep already removed it; nothing to do
            continue
    return removed
